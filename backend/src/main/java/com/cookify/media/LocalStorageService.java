package com.cookify.media;

import lombok.extern.slf4j.Slf4j;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Service;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.UUID;
import java.util.regex.Pattern;

/** Development storage: files under {@code app.storage.local-dir}, served at {@code /media/**}. */
@Slf4j
@Service
@ConditionalOnProperty(name = "app.storage.type", havingValue = "local", matchIfMissing = true)
public class LocalStorageService implements StorageService {

    /** Keys are always generated by us; anything else (e.g. "../") is rejected. */
    private static final Pattern SAFE_KEY = Pattern.compile("^[a-z0-9-]+(/[a-z0-9-]+)*/[0-9a-f-]{36}\\.[a-z0-9]{2,5}$");

    private final Path root;
    private final String publicBaseUrl;

    public LocalStorageService(StorageProperties props) {
        this.root = Path.of(props.localDir()).toAbsolutePath().normalize();
        this.publicBaseUrl = props.publicBaseUrl().replaceAll("/+$", "");
    }

    public Path root() {
        return root;
    }

    @Override
    public StoredFile store(String folder, byte[] bytes, String contentType, String extension) {
        String key = folder + "/" + UUID.randomUUID() + "." + extension;
        Path target = resolve(key);
        try {
            Files.createDirectories(target.getParent());
            Files.write(target, bytes);
        } catch (IOException e) {
            throw new UncheckedIOException("Could not store file " + key, e);
        }
        return new StoredFile(key, publicBaseUrl + "/" + key);
    }

    @Override
    public void delete(String key) {
        if (key == null) {
            return;
        }
        try {
            Files.deleteIfExists(resolve(key));
        } catch (IOException e) {
            log.warn("Could not delete stored file {}", key, e);
        }
    }

    private Path resolve(String key) {
        if (!SAFE_KEY.matcher(key).matches()) {
            throw new IllegalArgumentException("Unsafe storage key: " + key);
        }
        Path path = root.resolve(key).normalize();
        if (!path.startsWith(root)) {
            throw new IllegalArgumentException("Storage key escapes root: " + key);
        }
        return path;
    }
}
